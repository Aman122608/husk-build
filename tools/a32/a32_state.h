/*
 * a32_state.h -- the SINGLE definition of the record a test case leaves behind.
 *
 * Both sides of the differential harness include this file so there is exactly
 * one memory layout: the qemu-arm oracle (ubuntu job) fills a `struct a32_result`
 * per case and serialises it to a golden; the macos-26 compare job loads the same
 * goldens. When the translator lands it will produce `struct a32_result` too, and
 * the comparer diffs the two structs field by field with no second definition to
 * drift.
 *
 * ---------------------------------------------------------------------------
 * Case format (this increment: the case is compiled into the oracle ELF)
 * ---------------------------------------------------------------------------
 * A "case" is a hand-written ARM-mode fragment plus an initial register state.
 * It is generated by tools/a32/gen_cases.py, which emits one function per case in
 * tools/a32/a32_cases_gen.S with this ABI:
 *
 *     void a32_case_<id>(struct a32_result *out  // r0
 *                        void *scratch);         // r1
 *
 * The wrapper the generator emits:
 *   - saves r4-r11, lr;
 *   - puts &out->regs[0] (out + A32_OFF_REGS) in r12 and scratch in r9;
 *   - forces a known incoming flag state: mov r0,#0 ; cmp r0,#0  => N=0 Z=1 C=1 V=0
 *     (init only ever uses mov/movw/movt/ldr, none of which touch flags);
 *   - loads the case's initial r0..r8,r10,r11 (see below) with movw/movt;
 *   - runs the case body (the body must not touch r9 or r12);
 *   - captures r0..r11 with `stm r12,{r0-r11}`, cpsr with `mrs`, and zeroes the
 *     r12/r13/r14/r15 slots.
 *
 * Reserved registers, so the body never clobbers harness state:
 *   r9  = scratch window base   (an ADDRESS: recorded, never compared)
 *   r12 = out + A32_OFF_REGS    (an ADDRESS: recorded, forced to 0)
 * The comparable general-purpose registers are therefore r0-r8, r10, r11.
 * r13/r14/r15 are written 0 and are not compared in this increment; branch
 * semantics are asserted through GPRs instead (a branch case sets a register on
 * the path it takes), so no PC-offset handling is needed yet.
 *
 * Extension points (named, not wired in this increment):
 *   - `source` "handwritten" -> later "lifted"; tools/a32/extract.py will cut
 *     functions out of lib/armeabi-v7a/*.so (libLive2DCubismCore.so first) and
 *     emit the same case ABI, so nothing downstream changes but the tag.
 *   - step_limit/stop_reason: a generated case may loop; A32_STOP_LIMIT marks a
 *     case that ran away, which the comparer must treat as a failure, not a match.
 *
 * ---------------------------------------------------------------------------
 * Golden format (a32-goldens/1, written by a32oracle.c)
 * ---------------------------------------------------------------------------
 * JSON, one object per case:
 *   { "id":N, "name":"...", "regs":["0x........", x16],
 *     "cpsr":"0x........", "nzcvq":"0x........",
 *     "fpscr":"0x........", "fpscr_masked":"0x........",
 *     "fp":["0x................", x32],           // s0..s31, zero-extended
 *     "mem_size":4096, "mem_hash":"0x........",
 *     "mem_first_diff":"0x00000000", "stop_reason":0 }
 * Every 32/64-bit value is a hex STRING so it survives any JSON reader exactly;
 * only id/count/mem_size/stop_reason are JSON numbers. `nzcvq` is cpsr masked to
 * the architectural flags AArch32 user mode defines (NZCV + Q), and
 * `fpscr_masked` is fpscr masked to its architectural bits (A32_FPSCR_MASK); the
 * raw values ride along for debugging but are NEVER compared -- the whole reason
 * a raw cpsr or fpscr must never be compared is that the mode/IRQ and reserved
 * bits differ between any two implementations.
 */
#ifndef A32_STATE_H
#define A32_STATE_H

#include <stdint.h>

#define A32_NREG 16
#define A32_NFP  32

/* The scratch window both the oracle and (later) the translator honour. */
#define A32_MEM_SIZE 4096u

/* Byte offsets inside struct a32_result. The generated assembly hard-codes
 * A32_OFF_REGS; keep these in step with the struct and a static assert catches it. */
#define A32_OFF_FP        0u     /* uint64_t fp[32]   -> 0..255   */
#define A32_OFF_ID      256u     /* uint32_t id                   */
#define A32_OFF_REGS    260u     /* uint32_t regs[16] -> 260..323 */
#define A32_OFF_CPSR    324u     /* uint32_t cpsr                 */
#define A32_OFF_FPSCR   328u     /* uint32_t fpscr                */
#define A32_OFF_MSIZE   332u     /* uint32_t mem_size             */
#define A32_OFF_MHASH   336u     /* uint32_t mem_hash             */
#define A32_OFF_MDIFF   340u     /* uint32_t mem_first_diff       */
#define A32_OFF_STOP    344u     /* uint32_t stop_reason          */

/* cpsr bits AArch32 user mode defines and both sides must agree on: NZCV + Q,
 * plus the T (Thumb state) bit -- a state-transition bug must not pass, so the
 * entry/exit instruction-set state is part of the compared record. In ARM state
 * T is 0 on both sides, so this does not change any A32 case's compared value. */
#define A32_CPSR_MASK 0xF8000020u

/* FPSCR bits that are architectural state (NZCV, QC, AHP, DN, FZ, RMode, Stride,
 * Len, and the cumulative-exception flags); the reserved bits differ between any
 * two implementations, so a raw FPSCR must never be compared. */
#define A32_FPSCR_MASK 0xFFFF9F9Fu

struct a32_result {
    uint64_t fp[A32_NFP];     /* 0    s0..s31 raw bits, zero-extended into u64 */
    uint32_t id;              /* 256 */
    uint32_t regs[A32_NREG];  /* 260  r0..r15; r9=scratch addr, r12-r15 = 0 here */
    uint32_t cpsr;            /* 324  raw CPSR after the case                    */
    uint32_t fpscr;           /* 328  raw FPSCR after the case                   */
    uint32_t mem_size;        /* 332  scratch bytes covered by mem_hash          */
    uint32_t mem_hash;        /* 336  FNV-1a over the scratch window             */
    uint32_t mem_first_diff;  /* 340  0 in a golden; set by the comparer         */
    uint32_t stop_reason;     /* 344  A32_STOP_*                                 */
    uint32_t pad;             /* 348  keeps sizeof at 352 (8-aligned)            */
};

/* stop_reason: how the case ended. A truncated case is a failure, not a match. */
#define A32_STOP_RETURN 0u   /* ran to the end of the fragment (this increment) */
#define A32_STOP_FAULT  1u   /* illegal instruction / memory fault              */
#define A32_STOP_LIMIT  2u   /* hit step_limit (a generated loop that ran away) */

/* Compiled where sizeof(struct a32_result) is known, so the asm offsets cannot
 * silently disagree with the struct. */
#define A32_STATIC_ASSERT(cond, msg) typedef char a32_static_assert_##msg[(cond) ? 1 : -1]
A32_STATIC_ASSERT(sizeof(struct a32_result) == 352, result_is_352_bytes);

#endif /* A32_STATE_H */
